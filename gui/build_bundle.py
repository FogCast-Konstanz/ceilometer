"""Build the GUI's checked-in classic-script bundle without external tools."""
import argparse
import json
import re
from pathlib import Path

root=Path(__file__).resolve().parent
def module(filename,imports=''):
    source=(root/filename).read_text(encoding='utf-8')
    names=re.findall(r'^export (?:class|function|const) (\w+)',source,re.M)
    source=re.sub(r'^import .*?;\r?\n','',source,flags=re.M)
    source=re.sub(r'^export ','',source,flags=re.M)
    return '(()=>{\n'+imports+'\n'+source+'\nreturn {'+','.join(names)+'};\n})()'

protocol=module('protocol.mjs')
plot=module('plot.mjs')
demo=module('demo.mjs','const {DeviceError,integer}=protocol;')
app=(root/'app.mjs').read_text(encoding='utf-8')
app=re.sub(r'^import .*?;\r?\n','',app,flags=re.M)
old="  const response = await fetch('./demo-metadata.json'); if (!response.ok) throw new Error('Demo metadata unavailable.');\n  const port = new DemoPort(await response.json());"
assert old in app,'Demo metadata loader changed; update bundler.'
app=app.replace(old,'  const port = new DemoPort(demoMetadata);')
metadata=json.dumps(json.loads((root/'demo-metadata.json').read_text(encoding='utf-8')),ensure_ascii=True,separators=(',',':'))
bundle='// Generated by build_bundle.py; edit the .mjs sources, then rebuild.\n(()=>{\n"use strict";\n'
bundle+='const protocol='+protocol+';\nconst plot='+plot+';\nconst demoModule='+demo+';\n'
bundle+='const {SerialClient,DeviceError,Cancelled,integer,fields,telemetry,settingCommand,capturePage,csv}=protocol;\nconst {Scope,colors}=plot;\nconst {DemoPort}=demoModule;\nconst demoMetadata='+metadata+';\n'+app+'\n})();\n'
parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
target=root/'app.bundle.js'
if args.check:
    if not target.exists() or target.read_text(encoding='utf-8')!=bundle:raise SystemExit('GUI bundle is stale. Run python gui/build_bundle.py.')
else:
    target.write_text(bundle,encoding='utf-8')
    print(target)
